function frameSingleLineArt(lines: string[], footer: string) {
  const innerWidth = Math.max(
    footer.length,
    ...lines.map((line) => line.length),
  );

  return [
    `┌${"─".repeat(innerWidth + 2)}┐`,
    ...lines.map((line) => `│ ${line.padEnd(innerWidth)} │`),
    `├${"─".repeat(innerWidth + 2)}┤`,
    `│ ${footer.padEnd(innerWidth)} │`,
    `└${"─".repeat(innerWidth + 2)}┘`,
  ];
}

function frameDoubleLineArt(lines: string[], footer: string) {
  const innerWidth = Math.max(
    footer.length,
    ...lines.map((line) => line.length),
  );

  return [
    `╔${"═".repeat(innerWidth + 2)}╗`,
    ...lines.map((line) => `║ ${line.padEnd(innerWidth)} ║`),
    `╠${"═".repeat(innerWidth + 2)}╣`,
    `║ ${footer.padEnd(innerWidth)} ║`,
    `╚${"═".repeat(innerWidth + 2)}╝`,
  ];
}

